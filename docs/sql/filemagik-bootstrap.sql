-- FileMagik standalone database bootstrap. Review and run in a NEW dedicated Supabase project.
-- Never run against an existing application without confirming the target.
create table if not exists public.filemagik_admins (
 user_id uuid primary key references auth.users(id) on delete cascade,
 created_at timestamptz not null default now()
);
alter table public.filemagik_admins enable row level security;
create policy "admin can read own membership" on public.filemagik_admins for select to authenticated using (user_id=(select auth.uid()));

create table if not exists public.filemagik_settings (
 key text primary key,
 value jsonb not null default '{}'::jsonb,
 updated_at timestamptz not null default now(),
 updated_by uuid references auth.users(id)
);
alter table public.filemagik_settings enable row level security;
create policy "read public ads or own admin settings" on public.filemagik_settings
 for select to anon,authenticated using (
  key='ads_public' or exists (select 1 from public.filemagik_admins a where a.user_id=(select auth.uid()))
 );
create policy "admin can create settings" on public.filemagik_settings
 for insert to authenticated with check (exists(select 1 from public.filemagik_admins a where a.user_id=(select auth.uid())));
create policy "admin can update settings" on public.filemagik_settings
 for update to authenticated
 using (exists(select 1 from public.filemagik_admins a where a.user_id=(select auth.uid())))
 with check (exists(select 1 from public.filemagik_admins a where a.user_id=(select auth.uid())));

create table if not exists public.filemagik_admin_audit (
 id bigint generated by default as identity primary key,
 actor uuid not null references auth.users(id),
 action text not null,
 resource text not null,
 details jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);
alter table public.filemagik_admin_audit enable row level security;
create policy "admin can read audit" on public.filemagik_admin_audit
 for select to authenticated using (exists(select 1 from public.filemagik_admins a where a.user_id=(select auth.uid())));
create policy "admin can append audit" on public.filemagik_admin_audit
 for insert to authenticated with check (actor=(select auth.uid()) and exists(select 1 from public.filemagik_admins a where a.user_id=(select auth.uid())));

revoke all on public.filemagik_admins from anon;
grant select on public.filemagik_admins to authenticated;
grant select on public.filemagik_settings to anon,authenticated;
grant insert,update on public.filemagik_settings to authenticated;
grant select,insert on public.filemagik_admin_audit to authenticated;
grant usage,select on sequence public.filemagik_admin_audit_id_seq to authenticated;

insert into public.filemagik_settings(key,value)
values ('ads_public','{"enabled":false,"banners":[]}'::jsonb)
on conflict(key) do nothing;

