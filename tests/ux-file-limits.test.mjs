import assert from 'node:assert/strict';
import test from 'node:test';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';
const src=readFileSync('src/lib/file-limits.ts','utf8').replace(/import type .*?;\s*/g,'').replaceAll('export function','function').replaceAll('export type','type ');
const script=ts.transpileModule(src,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.None}}).outputText;
const sandbox={};vm.createContext(sandbox);vm.runInContext(script+';globalThis.api={limitsFor,validateFiles,sizeLimitLabel}',sandbox);
const {limitsFor,validateFiles,sizeLimitLabel}=sandbox.api;
const mb=n=>({size:n*1024*1024});
test('single common files accept 100MB',()=>assert.doesNotThrow(()=>validateFiles('split-pdf',[mb(95)])));
test('large PDF merger accepts 200MB total',()=>assert.doesNotThrow(()=>validateFiles('merge-pdf',[mb(99),mb(99)])));
test('oversize files report the applicable maximum',()=>assert.throws(()=>validateFiles('split-pdf',[mb(105)]),/100 MB/));
test('heavy OCR uses smaller browser safety ceiling',()=>assert.equal(limitsFor('ocr-pdf').perFile,60*1024*1024));
test('archive size is independent from browser raster operations',()=>assert.equal(sizeLimitLabel('create-zip'),'120 MB / 120 MB total'));
test('combined size and count are enforced',()=>{assert.throws(()=>validateFiles('merge-pdf',[mb(90),mb(90),mb(60)]),/Total/);assert.throws(()=>validateFiles('split-pdf',[mb(1),mb(1)]),/Too many/);});
const page=readFileSync('src/app/[locale]/[slug]/page.tsx','utf8');
test('unrelated recommendations and repeated FAQ are absent',()=>{for(const part of ['related-links','copy.question','copy.answer','Otras herramientas útiles'])assert.equal(page.includes(part),false);});
const home=readFileSync('src/app/[locale]/page.tsx','utf8');
test('circular studio is above the optional automatic upload',()=>assert.ok(home.indexOf('<RadialStudio')<home.indexOf('<SmartDropzone')));
test('ads are gated by verified account and publisher CMP',()=>{const code=readFileSync('src/lib/advertising/adsense.ts','utf8');for(const flag of ['SITE_APPROVED','CMP_VERIFIED','ADSENSE_ENABLED'])assert.ok(code.includes(flag));});
